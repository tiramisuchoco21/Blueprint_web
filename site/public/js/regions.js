export function regionName(zip) {
  for (const s of SIDO) {
    if (zip === s.code) return s.name;
    const list = SIGUNGU[s.code] || [];
    const hit = list.find(([c]) => c === zip);
    if (hit) return `${s.name} ${hit[1]}`;
  }
  return zip;
}
